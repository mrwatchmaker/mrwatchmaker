static lang_t languages[] = {
    {"English", "en", dict_en},
    {"한국어", "ko", dict_ko},
    {"日本語", "ja", dict_ja},
    {"中文", "zh", dict_zh},
    {"Français", "fr", dict_fr}
};

static int current_lang_idx = 0;

void i18n_init(int lang_idx) {
    if (lang_idx >= 0 && lang_idx < (int)(sizeof(languages)/sizeof(languages[0]))) {
        current_lang_idx = lang_idx;
        return;
    }
    
    // Auto-detect system language
    LANGID langid = GetUserDefaultUILanguage();
    int primary = PRIMARYLANGID(langid);
    switch (primary) {
        case LANG_KOREAN: current_lang_idx = 1; break;
        case LANG_JAPANESE: current_lang_idx = 2; break;
        case LANG_CHINESE: current_lang_idx = 3; break;
        case LANG_FRENCH: current_lang_idx = 4; break;
        default: current_lang_idx = 0; break; // Default to English
    }
}

const char *_(const char *key) {
    dict_entry_t *entry = languages[current_lang_idx].dict;
    while (entry->key != NULL) {
        if (strcmp(entry->key, key) == 0) {
            return entry->val;
        }
        entry++;
    }
    return key; // fallback
}

int i18n_get_current_lang(void) {
    return current_lang_idx;
}

int i18n_get_num_langs(void) {
    return sizeof(languages)/sizeof(languages[0]);
}

const char *i18n_get_lang_name(int idx) {
    if (idx >= 0 && idx < (int)(sizeof(languages)/sizeof(languages[0]))) {
        return languages[idx].name;
    }
    return "";
}
